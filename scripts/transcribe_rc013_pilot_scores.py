def build_score(composer: str, opus: str, mov: int, output_path: str) -> None:
    absolute_output = os.path.abspath(output_path)
    if (
        absolute_output == CANONICAL_RC013_DIR
        or absolute_output.startswith(CANONICAL_RC013_DIR + os.sep)
    ):
        raise RuntimeError(
            "QUARANTINED: template-generated candidates may not be written "
            "to data/scores/rc013/canonical."
        )
    title, key_str, meter_str, tempo_str, bars = PILOT_REGISTRY[(composer, opus, mov)]

    score = m21.stream.Score()
    score.metadata = m21.metadata.Metadata()
    score.metadata.title = f"{title} ({opus}, No. {mov})"
    score.metadata.composer = composer

    # Upper staff
    p_treble = m21.stream.PartStaff()
    p_treble.id = "P1"
    p_treble.partName = "Piano Right Hand"
    clef_treble = m21.clef.TrebleClef()

    # Lower staff
    p_bass = m21.stream.PartStaff()
    p_bass.id = "P2"
    p_bass.partName = "Piano Left Hand"
    clef_bass = m21.clef.BassClef()

    staff_group = m21.layout.StaffGroup([p_treble, p_bass], name="Piano", abbreviation="Pno.", symbol="brace")
    score.insert(0, staff_group)

    ks = m21.key.Key(key_str)
    ts = m21.meter.TimeSignature(meter_str)
    tempo = m21.tempo.MetronomeMark(text=tempo_str, number=92)

    for m_idx, (rh_notes, lh_notes) in enumerate(bars, start=1):
        m_rh = m21.stream.Measure(number=m_idx)
        m_lh = m21.stream.Measure(number=m_idx)

        if m_idx == 1:
            m_rh.insert(0, clef_treble)
            m_rh.insert(0, ks)
            m_rh.insert(0, ts)
            m_rh.insert(0, tempo)

            m_lh.insert(0, clef_bass)
            m_lh.insert(0, ks)
            m_lh.insert(0, ts)

        for pitch_str, dur in rh_notes:
            n = m21.note.Note(pitch_str)
            n.quarterLength = dur
            m_rh.append(n)

        for pitch_str, dur in lh_notes:
            n = m21.note.Note(pitch_str)
            n.quarterLength = dur
            m_lh.append(n)

        p_treble.append(m_rh)
        p_bass.append(m_lh)

    score.insert(0, p_treble)
    score.insert(0, p_bass)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    score.write("musicxml", fp=output_path)
    print(f"[TRANSCRIPTION COMPLETE] {output_path} ({len(bars)} measures, {composer} {opus} #{mov})")


